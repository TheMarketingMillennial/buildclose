/**
 * Build step for agency-proposals.com (client-facing proposal hosting).
 *
 * The proposal document is a template (`abrica.src.html`) carrying three
 * placeholders. This script fills them from the environment and writes the
 * deployable page into `dist/`.
 *
 * WHY A TEMPLATE RATHER THAN A HARDCODED PAGE
 *   A prospect access token is a credential. If it were committed into the HTML
 *   it would live in git history, in Netlify build logs, and in any archive of
 *   the repo — and it could never be rotated without a commit. Injecting it at
 *   build time means the token exists only in the deployed artefact, and rotating
 *   it is an environment-variable change.
 *
 * WHY THIS ALSO WRITES `_headers`
 *   The Content-Security-Policy has to name the assistant origin in `script-src`
 *   and `frame-src`. That origin is environment-specific (emulator vs agent.
 *   buildclose.app), so a static `_headers` file cannot be correct in both. It is
 *   generated here from the same variable that fills the widget tag, which is the
 *   only way the policy and the markup cannot drift apart.
 *
 * Required environment:
 *   PROPOSAL_TOKEN        bc_pk_… access token for this prospect (secret-ish)
 *   AGENT_ORIGIN          e.g. https://agent.buildclose.app
 *
 * Optional:
 *   PAYMENT_URL           commencement payment link; the button is hidden if unset
 *   PROPOSAL_SLUG         output name, default "abrica"
 *   ALLOW_PAYMENT_IFRAME  "true" also permits Stripe in frame-src
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const slug = (process.env.PROPOSAL_SLUG || 'abrica').replace(/[^a-z0-9-]/gi, '');
const agentOrigin = (process.env.AGENT_ORIGIN || 'https://agent.buildclose.app').replace(/\/+$/, '');
const token = (process.env.PROPOSAL_TOKEN || '').trim();
const paymentUrl = (process.env.PAYMENT_URL || '').trim();

function fail(message) {
  console.error(`\n[proposals] BUILD FAILED\n  ${message}\n`);
  process.exit(1);
}

if (!/^https?:\/\/[^/]+$/.test(agentOrigin)) {
  fail(`AGENT_ORIGIN must be a bare origin like https://agent.buildclose.app — got: ${agentOrigin}`);
}
if (!/^bc_pk_[A-Za-z0-9_-]{20,}$/.test(token)) {
  fail(
    'PROPOSAL_TOKEN is missing or malformed (expected bc_pk_…).\n' +
      '  Mint one with the `mintAccessToken` callable, or run `npm run seed` locally\n' +
      '  and copy the token it prints. Never commit a real token.',
  );
}
if (paymentUrl && !/^https:\/\/\S+$/.test(paymentUrl)) {
  fail(`PAYMENT_URL must be an https URL — got: ${paymentUrl}`);
}

let html = readFileSync(new URL('./abrica.src.html', import.meta.url), 'utf8');

// A placeholder left in the output would ship a literal "__BC_TOKEN__" to a
// prospect, so the replacement count is asserted rather than assumed.
const replacements = [
  ['__BC_TOKEN__', token, 1],
  ['__BC_AGENT_ORIGIN__', agentOrigin, 2],
  ['__BC_PAY_URL__', paymentUrl || '#', 1],
];

for (const [needle, value, expected] of replacements) {
  const found = html.split(needle).length - 1;
  if (found !== expected) {
    fail(`expected ${expected} "${needle}" placeholder(s), found ${found}. The template and build.mjs disagree.`);
  }
  html = html.split(needle).join(value);
}
if (html.includes('__BC_')) fail('a __BC_ placeholder survived substitution');

mkdirSync(new URL('./dist/proposals/', import.meta.url), { recursive: true });
writeFileSync(new URL(`./dist/proposals/${slug}.html`, import.meta.url), html, 'utf8');
writeFileSync(
  new URL('./dist/proposal.js', import.meta.url),
  readFileSync(new URL('./proposal.js', import.meta.url), 'utf8'),
  'utf8',
);

/**
 * Security headers.
 *
 * `frame-ancestors 'none'` — the proposal page is the top-level document; it must
 * never itself be framed, which is what stops a clickjacking overlay from
 * capturing the acceptance click.
 *
 * `script-src 'self' <agent>` — only our own script and the widget loader. No
 * 'unsafe-inline': the revenue calculator was moved to /proposal.js for exactly
 * this reason.
 *
 * `frame-src <agent>` — the assistant iframe may only be loaded from the chat
 * origin, so a compromised page cannot swap in a frame that harvests input.
 *
 * NOTE: no X-Frame-Options here. XFO cannot express "may be framed by nobody but
 * may frame my own assistant", and Netlify merges header rules, so adding it
 * would either be ignored (CSP wins) or break the widget. The CSP above is the
 * precise control.
 */
const frameSrc = [`'self'`, agentOrigin, paymentUrl ? 'https://checkout.stripe.com' : null]
  .filter(Boolean)
  .join(' ');

const headers = `# Generated by build.mjs — do not edit by hand.
/* 
  Content-Security-Policy: default-src 'self'; script-src 'self' ${agentOrigin}; frame-src ${frameSrc}; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data:; connect-src 'self' ${agentOrigin}; frame-ancestors 'none'; base-uri 'none'; form-action 'self' https://checkout.stripe.com
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), microphone=(), camera=()
  Cache-Control: no-store

/proposal.js
  Content-Type: text/javascript; charset=utf-8
  Cache-Control: public, max-age=300
`;
writeFileSync(new URL('./dist/_headers', import.meta.url), headers, 'utf8');

console.log(
  `[proposals] built dist/proposals/${slug}.html\n` +
    `  agent origin  ${agentOrigin}\n` +
    `  payment       ${paymentUrl || '(hidden — PAYMENT_URL not set)'}\n` +
    `  token         ${token.slice(0, 10)}… (${token.length} chars)`,
);
