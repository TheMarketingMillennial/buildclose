/**
 * Build step for agent.buildclose.app (the chatbot origin).
 *
 * Generates config.js, which injects the Cloud Functions endpoint at deploy time
 * so the same source works against the emulator, a staging project, and
 * production without editing tracked files. Nothing secret is emitted — the
 * functions base URL is public information, and every /api call is authorised by
 * a proposal token, not by anything in this file.
 *
 * Run from the app directory (Netlify sets the base directory per site):
 *     node build.mjs
 */
import { writeFileSync } from 'node:fs';

const projectId = process.env.FIREBASE_PROJECT_ID || 'buildclose-d4399';
const region = process.env.FUNCTIONS_REGION || 'us-central1';

/**
 * Cloud Functions gen 2 serves each function at
 *   https://<region>-<projectId>.cloudfunctions.net/<functionName>
 *
 * The exported function is named `api` and its routes carry an /api prefix, so a
 * bootstrap call resolves to .../api/api/bootstrap. That double segment is
 * intentional here: the outer /api is the function name, the inner one is the
 * router prefix. The chat client appends /api/bootstrap to this base.
 */
const apiBase = process.env.API_BASE || `https://${region}-${projectId}.cloudfunctions.net/api`;

if (!/^https?:\/\//.test(apiBase)) {
  throw new Error(`API_BASE must be an absolute URL, got: ${apiBase}`);
}

const banner = `/* Generated by build.mjs — do not edit. See build.mjs for the source. */\n`;
const body = `window.__BC_API_BASE__ = ${JSON.stringify(apiBase)};\n`;

writeFileSync(new URL('./config.js', import.meta.url), banner + body, 'utf8');
console.log(`[agent] config.js written -> API base ${apiBase}`);
