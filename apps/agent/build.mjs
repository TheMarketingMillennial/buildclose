/**
 * Build step for agent.buildclose.app (the chatbot origin).
 *
 * Emits a `dist/` directory containing the deployable site:
 *   dist/widget.js        the loader pasted into proposal pages
 *   dist/embed/…          the framed chat app
 *   dist/src/api.js       its API client
 *   dist/config.js        generated: API base URL
 *   dist/_headers         generated: CSP, CORS for the loader
 *
 * WHY THE HEADERS ARE GENERATED HERE RATHER THAN HAND-WRITTEN
 * Two values in the policy are environment-specific and must agree with
 * config.js exactly, or the site breaks in a way that is hard to diagnose:
 *
 *   connect-src   must name the Cloud Functions host the client actually calls.
 *                 When this was a static file it named the production host, so
 *                 every emulator run was blocked by CSP with a connect-src
 *                 violation that looked like a network fault.
 *   frame-ancestors  must admit the origin hosting the proposal page. Production
 *                 is https-only; a local run embeds from http://localhost:8890,
 *                 which `frame-ancestors https:` rejects outright.
 *
 * Deriving both from the same variables removes the whole class of drift.
 *
 * Run from the app directory (Netlify sets the base directory per site):
 *     node build.mjs
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const projectId = process.env.FIREBASE_PROJECT_ID || 'buildclose-d4399';
const region = process.env.FUNCTIONS_REGION || 'us-central1';

/**
 * Cloud Functions gen 2 serves each function at
 *   https://<region>-<projectId>.cloudfunctions.net/<functionName>
 *
 * The exported function is named `api` and its routes carry an /api prefix, so a
 * bootstrap call resolves to .../api/api/bootstrap. That double segment is
 * intentional: the outer /api is the function name, the inner one the router
 * prefix. The chat client appends /api/bootstrap to this base.
 */
const apiBase = process.env.API_BASE || `https://${region}-${projectId}.cloudfunctions.net/api`;
if (!/^https?:\/\/\S+$/.test(apiBase)) {
  throw new Error(`API_BASE must be an absolute URL, got: ${apiBase}`);
}

// Origin of the Cloud Functions deployment (scheme + host), for connect-src.
const apiOrigin = new URL(apiBase).origin;

/**
 * Who may frame the chat app.
 *
 * Default is the production posture: https only, because every real embed is an
 * https proposal page. A local run sets EMBED_FRAME_ANCESTORS to the http
 * origin of the local proposal server. Never widen this to `*` — the CSP is the
 * only thing preventing an arbitrary site from framing the assistant, and a
 * wildcard would also let a page frame it invisibly over its own click targets.
 */
const frameAncestors = process.env.EMBED_FRAME_ANCESTORS || 'https:';

const headers = `# Generated by build.mjs — do not edit by hand.
#
# The loader is fetched cross-origin by customer pages, so it must be CORS-open.
# It carries no secrets: the proposal token is supplied by the customer's own HTML
# attribute and verified server-side on every call.
/widget.js
  Access-Control-Allow-Origin: *
  Cache-Control: public, max-age=300, stale-while-revalidate=86400
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer

# Everything else on this origin is the framed chat app: never cached (it holds a
# session in memory), never sniffed, and framable only by the proposal host.
#
# Both /embed and /embed/* are listed because header rules match the request path,
# and a rule that misses the actual document would silently serve it with no
# frame-ancestors at all.
#
# There is deliberately no X-Frame-Options anywhere in this file. Netlify merges
# matching rules, so a wildcard XFO would also apply here and block the iframe;
# CSP frame-ancestors is the precise control.
/embed
  Content-Security-Policy: default-src 'self'; connect-src 'self' ${apiOrigin}; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; frame-ancestors ${frameAncestors}; base-uri 'none'; form-action 'none'
  Cache-Control: no-store
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer

/embed/*
  Content-Security-Policy: default-src 'self'; connect-src 'self' ${apiOrigin}; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; frame-ancestors ${frameAncestors}; base-uri 'none'; form-action 'none'
  Cache-Control: no-store
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: geolocation=(), microphone=(), camera=(), payment=()
`;

const root = new URL('./', import.meta.url);
const dist = new URL('./dist/', import.meta.url);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

/**
 * Fail the build if any served script is not valid JavaScript.
 *
 * These files are shipped verbatim — there is no bundler or transpiler in front
 * of them — so a stray TypeScript annotation is a runtime SyntaxError in the
 * browser. Inside a sandboxed iframe that failure is close to invisible: the
 * widget mounts, the frame stays on "Connecting…", and nothing is logged to the
 * page the developer is looking at. It cost real debugging time once; this check
 * makes it a build failure instead.
 */
function assertValidEsm(relPath) {
  const abs = new URL(relPath, dist);
  let source = readFileSync(abs, 'utf8');
  // node --check resolves imports, so rewrite the relative specifier to the
  // sibling it was copied next to. Nothing is executed.
  source = source.replace(/from '(\.\.?\/[^']+)'/g, (_m, spec) => `from '${spec.replace(/\.js$/, '.mjs')}'`);
  const tmp = abs.pathname.replace(/\.js$/, '.check.mjs');
  writeFileSync(tmp, source, 'utf8');
  try {
    execFileSync(process.execPath, ['--check', tmp], { stdio: 'pipe' });
  } catch (err) {
    const detail = String(err.stderr || err.message).split('\n').slice(0, 6).join('\n');
    throw new Error(`${relPath} is not valid JavaScript (types must be JSDoc, not TS syntax):\n${detail}`);
  } finally {
    rmSync(tmp, { force: true });
  }
}

// Copy the static surface, leaving the build tooling and generated files behind.
for (const entry of ['widget.js', 'embed', 'src']) {
  cpSync(new URL(entry, root), new URL(entry, dist), { recursive: true });
}

for (const script of ['widget.js', 'src/api.js', 'embed/app.js']) {
  assertValidEsm(script);
}

writeFileSync(
  new URL('./config.js', dist),
  `/* Generated by build.mjs — do not edit. */\nwindow.__BC_API_BASE__ = ${JSON.stringify(apiBase)};\n`,
  'utf8',
);
writeFileSync(new URL('./_headers', dist), headers, 'utf8');

console.log(
  `[agent] built dist/ -> API base ${apiBase}\n` +
    `  connect-src       ${apiOrigin}\n` +
    `  frame-ancestors   ${frameAncestors}`,
);
