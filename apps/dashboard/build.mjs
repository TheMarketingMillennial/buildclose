/**
 * Build step for app.buildclose.app (the customer dashboard).
 *
 * Generates config.js from Netlify environment variables so no Firebase API key
 * is committed to the repository. These values are public identifiers, not
 * secrets — Firebase web config is designed to ship in the client. The actual
 * security boundary is Firestore Security Rules (default-deny; see
 * firestore.rules) plus the staff callables' custom-claims checks, not the key.
 *
 * Run from the app directory (Netlify sets the base directory per site):
 *     node build.mjs
 */
import { writeFileSync } from 'node:fs';

const projectId = process.env.FIREBASE_PROJECT_ID || 'buildclose-d4399';
const region = process.env.FUNCTIONS_REGION || 'us-central1';

const apiBase =
  process.env.API_BASE || `https://${region}-${projectId}.cloudfunctions.net/api`;

function required(name) {
  const v = process.env[name];
  if (!v || v.trim() === '') {
    throw new Error(
      `Missing ${name}. Set it in Netlify > Site configuration > Environment variables, ` +
        `or for a local build export it in your shell. Do not commit real values.`,
    );
  }
  return v.trim();
}

const config = {
  apiBase,
  firebase: {
    apiKey: required('FIREBASE_API_KEY'),
    authDomain: process.env.FIREBASE_AUTH_DOMAIN || `${projectId}.firebaseapp.com`,
    projectId,
    appId: required('FIREBASE_APP_ID'),
  },
};

const banner = `/* Generated by build.mjs — do not edit. See build.mjs for the source. */\n`;
const body = `window.__BC_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`;

writeFileSync(new URL('./config.js', import.meta.url), banner + body, 'utf8');
console.log(`[dashboard] config.js written -> API base ${apiBase}`);
